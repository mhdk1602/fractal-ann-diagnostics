"""v0.1.0 calibration on two ANN-benchmarks datasets.

Downloads MNIST-784-Euclidean and Fashion-MNIST-784-Euclidean from
ann-benchmarks.com, computes the descriptor panel on the training set
(subsampled to 2000 points), runs the recommender, and writes a markdown
table to ``experiments/calibration-v0.1.0.md``.

If the HDF5 downloads fail (offline sandbox, TLS issues, etc.) the script
falls back to a small synthetic Gaussian-mixture dataset so the pipeline
still runs end-to-end.
"""
from __future__ import annotations

import sys
from pathlib import Path

# Make the in-repo ``src/`` importable so this script runs from a clean
# checkout without requiring ``pip install -e .`` first.
_ROOT = Path(__file__).resolve().parent.parent
_SRC = _ROOT / "src"
if _SRC.exists() and str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))

import numpy as np  # noqa: E402

from fractal_ann_diagnostics.benchmark import load_ann_benchmark  # noqa: E402
from fractal_ann_diagnostics.diagnostic import diagnose  # noqa: E402

DATASETS = ("mnist-784-euclidean", "fashion-mnist-784-euclidean")
CACHE_DIR = Path.home() / ".cache" / "ann-benchmarks"
OUTPUT_PATH = Path(__file__).resolve().parent / "calibration-v0.1.0.md"
SAMPLE_SIZE = 2000


def _synthetic_gaussian_mixture(name: str, n: int = 2000, d: int = 64) -> np.ndarray:
    """Fallback dataset: a 4-component Gaussian mixture in R^d."""
    rng = np.random.default_rng(hash(name) & 0xFFFF_FFFF)
    n_per = n // 4
    centres = rng.standard_normal((4, d)) * 3.0
    parts = [rng.standard_normal((n_per, d)) + c for c in centres]
    x = np.vstack(parts).astype(np.float32)
    rng.shuffle(x)
    return x


def _try_load(name: str) -> tuple[np.ndarray, bool]:
    """Try the real ANN-benchmarks loader; fall back to synthetic on any error.

    Returns (train_vectors, used_fallback).
    """
    try:
        ds = load_ann_benchmark(name, CACHE_DIR)
        return ds.train, False
    except Exception as e:  # noqa: BLE001
        print(f"[warn] {name}: load failed ({type(e).__name__}: {e}); using synthetic fallback.")
        return _synthetic_gaussian_mixture(name), True


def main() -> None:
    rows: list[dict[str, str]] = []
    for name in DATASETS:
        print(f"--- {name} ---")
        train, used_fallback = _try_load(name)
        if used_fallback:
            display_name = f"{name} (synthetic fallback)"
        else:
            display_name = name
        print(f"  train shape: {train.shape}")

        result = diagnose(train, sample_size=SAMPLE_SIZE)
        panel = result.descriptors
        lid_p95 = float(np.quantile(panel.lid_distribution, 0.95))

        rows.append(
            {
                "dataset": display_name,
                "n": f"{panel.n_points}",
                "d": f"{panel.ambient_dimension}",
                "D2": f"{panel.correlation_dimension:.3f}",
                "lid_p95": f"{lid_p95:.3f}",
                "hubness": f"{panel.hubness_skew:.3f}",
                "mfw": (
                    f"{panel.multifractal_width:.3f}"
                    if np.isfinite(panel.multifractal_width)
                    else "nan"
                ),
                "recommended": result.recommended_index,
                "predicted_drop": f"{result.predicted_recall_drop:.3f}",
            }
        )
        print(f"  recommended: {result.recommended_index}")
        print(f"  rationale:   {result.rationale}")

    headers = [
        "dataset",
        "n",
        "d",
        "D2",
        "lid_p95",
        "hubness",
        "mfw",
        "recommended",
        "predicted_drop",
    ]
    lines = [
        "# v0.1.0 calibration",
        "",
        "Descriptor panel and rule-based recommendation on two ANN-benchmarks",
        "datasets (subsampled to 2000 points). Generated by",
        "`experiments/calibrate_v0_1_0.py`.",
        "",
        "| " + " | ".join(headers) + " |",
        "|" + "|".join(["---"] * len(headers)) + "|",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row[h] for h in headers) + " |")
    lines.append("")
    lines.append(
        "Note: `mfw` is α_max − α_min of the multifractal singularity spectrum "
        "from MFDFA on all-pairs distances. `predicted_drop` is meaningful only "
        "when the recommended index is `hnsw`; the other rules zero it out "
        "because v0.1.0 does not yet model recall drop on flat-NSW / IVF / "
        "DiskANN."
    )
    lines.append("")
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
